"""Generate `src/mspm0_parts.rs` from the mspm0-data catalog.

The pin-to-PINCM mapping is per part and is not an arithmetic function of the pin. It equals
`pin + 1` on 14 of the 43 parts and on the other 29 the difference ranges from -27 to +28, so a
table is the only correct answer. A second port continues the same PINCM numbering rather than
restarting, which is why the key here is (port, pin) and not a per-port index.

Usage:  uv run tools/generate_iomux.py [DATA_DIR] > src/mspm0_parts.rs
        DATA_DIR defaults to ~/git/mspm0-data-generated/data
"""

import json
import pathlib
import re
import sys

DEFAULT = pathlib.Path.home() / "git/mspm0-data-generated/data"
data = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT

parts = []
for path in sorted(data.glob("*.json")):
    chip = json.load(path.open())
    pins = []
    for name, pincm in chip["iomux"].items():
        m = re.fullmatch(r"P([A-Z])(\d+)", name)
        if not m:
            continue
        port = ord(m.group(1)) - ord("A")
        pins.append((port, int(m.group(2)), pincm))
    if pins:
        parts.append((chip["name"].lower(), sorted(pins)))

out = sys.stdout.write
out("""//! Which `PINCM` register each pin uses, per part.
//!
//! **Generated by `tools/generate_iomux.py` from the mspm0-data catalog. Do not edit.**
//!
//! # Why this is a table and not arithmetic
//!
//! `PINCM` indices are a per-part property. They equal `pin + 1` on 14 of the 43 parts here, and on
//! the other 29 the difference between a pin's number and its `PINCM` ranges from -27 to +28. A
//! second port continues the same numbering rather than restarting — on an `MSPM0L2228`, `PB0` is
//! `PINCM12` — so neither a per-port base nor an offset recovers it.
//!
//! # The value is TI's `PINCM<n>`, one-based
//!
//! It matches the datasheet pin tables, so `PA0` is `1` and not `0`. The register address is
//! `IOMUX + pincm * 4`: the array starts one register in, and that offset is already spent in the
//! multiplication. Adding a further `0x04` lands one register high on every pin, which reads as a
//! neighbouring pin's mux and looks entirely plausible.

/// `(port, pin, pincm)`, sorted, where port 0 is `PA`.
type Pins = &'static [(u8, u8, u8)];

""")

out(f"/// Every part in the catalog, by lowercased name.\npub static PARTS: [(&str, Pins); {len(parts)}] = [\n")
for name, pins in parts:
    body = ", ".join(f"({p},{n},{c})" for p, n, c in pins)
    out(f'    ("{name}", &[{body}]),\n')
out("];\n")
